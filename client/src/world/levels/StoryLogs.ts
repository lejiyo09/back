/** global recorder log index of a themed level's k-th recording (after the original seven) */
export function storyLogIndex(level: number, k: number): number {
  return 7 + (level - 3) * 2 + k;
}

export function allStoryLogs(): RecorderLog[] {
  const out: RecorderLog[] = [];
  for (let lv = 3; lv <= 10; lv++) out.push(...STORY_LOGS[lv]);
  return out;
}
